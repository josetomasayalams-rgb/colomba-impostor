import { readdir, readFile, writeFile, mkdir, cp, rm } from 'node:fs/promises';
import { extname, join } from 'node:path';
import { build } from 'esbuild';
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.woff2': 'font/woff2', '.webmanifest': 'application/manifest+json', '.png': 'image/png' };
const assets = {};
async function collect(directory, prefix = '') {
  for (const file of await readdir(directory, { withFileTypes: true })) {
    const relative = `${prefix}/${file.name}`, absolute = join(directory, file.name);
    if (file.isDirectory()) await collect(absolute, relative);
    else if (types[extname(file.name)]) assets[relative] = { type: types[extname(file.name)], data: (await readFile(absolute)).toString('base64') };
  }
}
await collect('public');
await writeFile('worker/assets.generated.mjs', `// Generated by scripts/build.mjs\nexport const assets = ${JSON.stringify(assets)};\n`);
await rm('dist', { recursive: true, force: true });
await mkdir('dist/server', { recursive: true }); await mkdir('dist/.openai', { recursive: true });
await build({ entryPoints: ['worker/index.js'], outfile: 'dist/server/index.js', bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true });
await cp('.openai/hosting.json', 'dist/.openai/hosting.json');
console.log(`Built portable Worker with ${Object.keys(assets).length} embedded assets.`);
